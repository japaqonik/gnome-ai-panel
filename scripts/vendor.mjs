// Copies the browser builds of the UI libraries from node_modules into app/ui/vendor/
// (PLAN §8: npm + vendoring, no CDN). The copies are byte-identical to the npm packages, so
// `make vendor && git status --porcelain app/ui/vendor` shows no changes when the committed
// files match package-lock.json. Also writes app/ui/vendor/vendor.json (package, version,
// license, SHA-256 of every file) and removes files that are no longer vendored.
//
// Fails (exit 1) when a package is missing or its installed version differs from the lock
// file; run `npm ci` first.
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendorDir = path.join(root, 'app', 'ui', 'vendor');

// [package, [[source path inside the package, file name in app/ui/vendor], ...]]
const PACKAGES = [
    ['marked', [
        ['lib/marked.umd.js', 'marked.umd.js'],
        ['LICENSE', 'LICENSE.marked.txt'],
    ]],
    ['dompurify', [
        ['dist/purify.min.js', 'purify.min.js'],
        ['LICENSE', 'LICENSE.dompurify.txt'],
        ['LICENSE-MPL', 'LICENSE-MPL.dompurify.txt'],
    ]],
    // Official prebuilt browser bundle of highlight.js (same project and version as the
    // `highlight.js` package, which ships only CommonJS/ES module sources). highlight.min.js
    // contains the "common" language set (bash, c, cpp, css, go, java, javascript, json,
    // python, rust, sql, typescript, xml, yaml and others).
    ['@highlightjs/cdn-assets', [
        ['highlight.min.js', 'highlight.min.js'],
        ['styles/github.min.css', 'github.min.css'],
        ['styles/github-dark.min.css', 'github-dark.min.css'],
        ['LICENSE', 'LICENSE.highlight.js.txt'],
    ]],
];

const MANIFEST = 'vendor.json';

function fail(message) {
    console.error(`vendor: ${message}`);
    process.exit(1);
}

function readJson(file) {
    try {
        return JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (error) {
        return fail(`cannot read ${path.relative(root, file)}: ${error.message}`);
    }
}

const lock = readJson(path.join(root, 'package-lock.json'));
const manifest = {
    comment: 'Generated by scripts/vendor.mjs from package-lock.json. Do not edit.',
    packages: [],
};
const written = new Set([MANIFEST]);

fs.mkdirSync(vendorDir, {recursive: true});

for (const [name, files] of PACKAGES) {
    const locked = lock.packages?.[`node_modules/${name}`];
    if (!locked)
        fail(`${name} is not in package-lock.json`);
    const pkgDir = path.join(root, 'node_modules', name);
    const installed = readJson(path.join(pkgDir, 'package.json'));
    if (installed.version !== locked.version)
        fail(`${name} ${installed.version} is installed but package-lock.json pins ${locked.version}; run npm ci`);

    const entry = {name, version: locked.version, license: locked.license ?? installed.license, files: {}};
    for (const [source, target] of files) {
        const data = fs.readFileSync(path.join(pkgDir, source));
        fs.writeFileSync(path.join(vendorDir, target), data);
        entry.files[target] = {
            source: `${name}/${source}`,
            sha256: createHash('sha256').update(data).digest('hex'),
        };
        written.add(target);
    }
    manifest.packages.push(entry);
}

fs.writeFileSync(path.join(vendorDir, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);

for (const file of fs.readdirSync(vendorDir)) {
    if (!written.has(file)) {
        fs.rmSync(path.join(vendorDir, file), {recursive: true});
        console.log(`vendor: removed stale ${file}`);
    }
}

for (const {name, version} of manifest.packages)
    console.log(`vendor: ${name}@${version}`);
